import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/authRoutes.js';
import studentRoutes from './routes/studentRoutes.js';
import collegeRoutes from './routes/collegeRoutes.js';
import productRoutes from './routes/productRoutes.js';
import measurementRoutes from './routes/measurementRoutes.js';
import tailorRoutes from './routes/tailorRoutes.js';
import orderRoutes from './routes/orderRoutes.js';
import reviewRoutes from './routes/reviewRoutes.js';
import adminRoutes from './routes/adminRoutes.js';
import { errorHandler, notFound } from './middleware/errors.js';

const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173', credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(morgan('dev'));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-8', legacyHeaders: false }));
app.get('/api/health', (req, res) => res.json({ status: 'ok', service: 'stichy-api' }));
app.use('/api/auth', authRoutes); app.use('/api/students', studentRoutes); app.use('/api/colleges', collegeRoutes);
app.use('/api/products', productRoutes); app.use('/api/measurements', measurementRoutes); app.use('/api/tailors', tailorRoutes);
app.use('/api/orders', orderRoutes); app.use('/api/reviews', reviewRoutes);
app.use('/api/admin', adminRoutes);
app.use(notFound); app.use(errorHandler);
export default app;
